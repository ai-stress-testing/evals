#!/usr/bin/env python3
"""Generate .claude/agents/<team>-<role>.md from the roster (GT-60).

The roster lives at agents/<team>/<role>/agent.md — a repo path the Claude
Code runtime does NOT discover subagents from. Claude Code discovers them at
.claude/agents/*.md. This build step flattens every roster charter into that
discovery path so each role becomes a real, callable `subagent_type` with its
least-privilege tool set and model intact. Without it the roster is inert
documentation (issue #59).

Deterministic + idempotent, the same discipline as build_index.py /
build_repo_index.py — so `personas_installed` (scripts/verifiers/) can assert
the install is fresh. Run from the repo root:

    python3 scripts/build_personas.py

Do NOT hand-edit files under .claude/agents/ — they are generated. Edit the
source agents/<team>/<role>/agent.md and regenerate.
"""
import glob
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_index  # noqa: E402  (reuse the roster's own parse + model resolution)

OUT_DIR = ".claude/agents"
GENERATED_NOTE = (
    "<!-- generated by scripts/build_personas.py from "
    "agents/{team}/{role}/agent.md — do not edit here; edit the source. -->"
)


def short_model(raw, tiers, aliases, concrete):
    """Resolve a roster `model:` (tier | alias | id) to the short name Claude
    Code accepts in a subagent's `model:` field (opus/sonnet/haiku/fable).
    Falls back to the raw value if it can't be resolved (build_index lints
    that case separately)."""
    resolved, _tier = build_index.resolve_model(raw, tiers, aliases, concrete)
    if resolved is None:
        return raw
    id_to_alias = {v: k for k, v in aliases.items()}
    return id_to_alias.get(resolved, resolved)


def split_frontmatter(text):
    """Return (frontmatter_dict, body_str) for an agent.md. build_index.parse
    reads by path; here we already have the text, so parse the block inline
    with the same naive splitter."""
    m = build_index.FM.match(text)
    fm = {}
    if m:
        for line in m.group(1).split("\n"):
            if ":" in line:
                k, v = line.split(":", 1)
                fm[k.strip()] = v.strip()
    body = text[m.end():].lstrip("\n") if m else text
    return fm, body


def render_all():
    """{slug: file_content} for every non-TEMPLATE role. Pure — no writes."""
    tiers, aliases = build_index.load_model_config()
    concrete = set(tiers.values()) | set(aliases.values())
    out = {}
    for path in sorted(glob.glob("agents/*/*/agent.md")):
        _, team, role, _ = path.split("/")
        if team == "TEMPLATE":
            continue
        slug = f"{team}-{role}"
        fm, body = split_frontmatter(open(path, encoding="utf-8").read())
        model = short_model(fm.get("model", ""), tiers, aliases, concrete)
        note = GENERATED_NOTE.format(team=team, role=role)
        lines = [
            "---",
            f"name: {slug}",
            f"description: {fm.get('description', '').strip()}",
            f"tools: {fm.get('tools', '').strip()}",
            f"model: {model}",
            "---",
            "",
            note,
            "",
            body.rstrip("\n"),
            "",
        ]
        out[slug] = "\n".join(lines)
    return out


def main():
    personas = render_all()
    os.makedirs(OUT_DIR, exist_ok=True)
    # Remove stale generated files (a role that was renamed/removed) so the
    # discovery path is an exact mirror of the roster.
    keep = {f"{slug}.md" for slug in personas}
    for existing in glob.glob(f"{OUT_DIR}/*.md"):
        if os.path.basename(existing) not in keep:
            os.remove(existing)
    for slug, content in personas.items():
        with open(f"{OUT_DIR}/{slug}.md", "w", encoding="utf-8") as f:
            f.write(content)
    print(f"wrote {OUT_DIR}: {len(personas)} personas")
    return 0


if __name__ == "__main__":
    sys.exit(main())
